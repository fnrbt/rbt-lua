-- string.format edge cases (C printf semantics)
local f = string.format
print(f("%.0f|%.0f|%.0f|%.0f|%.1f|%.2f|%.3f", 0.5, 1.5, 2.5, -0.5, 0.05, 1.005, 2.0005))
print(f("%g|%g|%g|%g|%g|%g|%g|%g", 1e-4, 1e-5, 100000, 1e6, 0.0001234, 123456, 1234567, -0.0))
print(f("%.3g|%.10g|%#g|%g|%g", 3.14159, 1/3, 1.0, 2^63, 1e100))
print(f("%e|%E|%.0e|%e|%e", 0.0, 123.456, 5.5, 1e-310, -1e300))
print(f("%10.3f|%-10.2e|%+.1f|% d|%+5d|%-5d|", math.pi, 1234.5, 2.25, 42, 7, -7))
print(f("%5s|%-5s|%.2s|%5.1s|%s", "ab", "ab", "abc", "xyz", true))
print(f("%x|%X|%#x|%o|%#o|%08.3f|%3c|", 3735928559, 48879, 255, 64, 8, -3.14159, 65))
print(f("%d|%d|%5.2d|%.0d", math.maxinteger, math.mininteger, 3, 0))
print(f("%q", "tab\there\nnewline \"quoted\" back\\slash \0001 nul\0end \r\127"))
print(f("%q|%q|%q|%q|%q", 0.5, -2.0, 1e300, true, nil))
print(f("%a|%a|%a|%.0a|%.1a|%.13a|%.15a", 1e-310, 2^-1074, 1.9999999999999998, 1.5, 1.96875, 0.1, 0.1))
print(f("%%|%c%c%c", 76, 117, 97), pcall(f, "%5%"))
print(f("%s %s %s", 1, 1.5, -0.0), f("%d", 3.0), pcall(f, "%d", 3.5))
print(tostring(1e100), tostring(-1e-100), tostring(123456789012345), tostring(0.1 + 0.2), 1e15 + 0.5, 2^53 + 1)
